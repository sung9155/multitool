export interface Match {
  recipe: Recipe;
  missing: string[]; // 없는 필수 재료
  optHave: string[]; // 보유한 선택 재료
}

/** 보유 재료로 각 레시피의 부족 재료 계산. 기본 양념은 항상 보유로 간주. */
export function matchRecipes(
  pantry: Iterable<string>,
  recipes: Recipe[] = RECIPES,
): Match[] {
  const have = new Set([...pantry, ...STAPLES]);
  return recipes
    .map((recipe) => ({
      recipe,
      missing: recipe.req.filter((i) => !have.has(i)),
      optHave: recipe.opt.filter((i) => have.has(i)),
    }))
    .sort(
      (a, b) =>
        a.missing.length - b.missing.length || a.recipe.min - b.recipe.min,
    );
}
