export function seasonalIngredients(month: number): string[] {
  return SEASONAL[month] ?? [];
}

/** 레시피에 쓰인 이달 제철 재료 */
export function seasonalOf(recipe: Recipe, month: number): string[] {
  const s = new Set(seasonalIngredients(month));
  return [...recipe.req, ...recipe.opt].filter((i) => s.has(i));
}

export interface Match {
  recipe: Recipe;
  missing: string[]; // 없는 필수 재료
  optHave: string[]; // 보유한 선택 재료
  seasonal: string[]; // 이달 제철 재료
}

/**
 * 보유 재료로 각 레시피의 부족 재료 계산. 기본 양념은 항상 보유로 간주.
 * 정렬: 부족 수 → (제철 우선이면 제철 재료 수 역순) → 조리시간
 */
export function matchRecipes(
  pantry: Iterable<string>,
  opts: { month?: number; seasonFirst?: boolean } = {},
  recipes: Recipe[] = RECIPES,
): Match[] {
  const have = new Set([...pantry, ...STAPLES]);
  const month = opts.month ?? 0;
  return recipes
    .map((recipe) => ({
      recipe,
      missing: recipe.req.filter((i) => !have.has(i)),
      optHave: recipe.opt.filter((i) => have.has(i)),
      seasonal: seasonalOf(recipe, month),
    }))
    .sort(
      (a, b) =>
        a.missing.length - b.missing.length ||
        (opts.seasonFirst ? b.seasonal.length - a.seasonal.length : 0) ||
        a.recipe.min - b.recipe.min,
    );
}
